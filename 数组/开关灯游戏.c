/*开关灯游戏：有n（假设不超过1000）盏灯从1到n按顺序依次编号，有n个人也从1到n依次编号，第一个人（1号）将灯全部关闭，第二个人（2号）将凡是2和2的倍数的灯打开，第三个人（3号）将凡是3和3的倍数的灯做相反处理（即该灯如为打开的，将它关闭；如为关闭的，将它打开）。以后的人都和3号一样，将凡是与自己相同编号的灯和是自己编号倍数的灯做相反处理。n 从键盘输入，请问：当第n个人操作之后，哪几盏灯是关闭的（输出其编号）。

【输入形式】输入一个正整数n

【输出形式】关闭的灯的编号，多个编号之间以一个空格分隔

【输入样例】5

【输出样例】1 4

【样例说明】

有5盏灯和5个人，按照游戏规则操作后1，4号灯是关闭的。*/
#include<stdio.h>
int main(void)
{
    int a[1000]={0},n,i,j;
    scanf("%d",&n);
    for (i=1;i<n;i++)
    {
        for (j=0;j<n;j++)
        {
            if ((j+1)%(i+1)==0)
            {
                if (a[j]==0)
                    a[j]=1;
                else
                    a[j]=0;
            }
        }
    }
    for (i=0;i<n;i++)
    {
        if (a[i]==0)
            printf("%d ",i+1);
    }
    return 0;
}
