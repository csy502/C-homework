/*编写程序，实现以下整数处理功能：

（1）输入10个整数；

（2）输出其中只出现一次的整数；

（3）计算并输出上述整数的平均值（保留小数点后一位小数）；

（4）如果没有出现一次的整数，则输出“No”提示。

【输入形式】

输入10个整数

【输出形式】

用一个空格分隔输出的数或输出No

【样例输入1】

30  30  100  2011  -80  2011  200  -80  2011  -80

【样例输出1】

100  200  150.0

【样例说明】

整数100与200只出现一次，其它整数出现多次，100和200的平均值是150.0

【样例输入2】

1 2 3 4 1 2 1 3 1 4

【样例输出2】

No

【样例说明】

输入整数中没有出现一次的整数，则输出“No”*/
#include<stdio.h>
int main(void)
{
    int a[10],i,j,n=0;
    double av=0;
    for (i=0;i<10;i++)
        scanf("%d",&a[i]);
    for (i=0;i<10;i++)
    {
        int t=0;
        for (j=0;j<10;j++)
        {
            if (a[i]==a[j])
                t++;
        }
        if (t==1)
        {
            printf("%d ",a[i]);
            n++;
            av+=a[i];
        }
    }
    if (n>0)
        printf("%.1lf",av/n);
    else
        printf("No");
    return 0;
}
