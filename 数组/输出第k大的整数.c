/*【问题描述】输入n（1<n≤100）个无序的且允许重复的整数，求解并输出其中第k大的整数，注意多个重复的数算作相同的一个数，且k的值不大于无重复整数的个数。

【输入形式】分3行输入，第1行输入n，第2行输入n个整数，第3行输入k

【输出形式】输出第k大的整数

【输入样例1】

5

12 34 56 34 23

3

【输出样例1】

23

【样例说明1】输入5个整数12 34 56 34 23，其中第3大的数是23（两个重复的34都算作第2大的数）。

【输入样例2】

6

10 -20 50 -30 40 60

5

【输出样例2】

-20

【样例说明2】输入6个整数10 -20 50 -30 40 60，其中第5大的数是-20。*/
#include<stdio.h>
int main(void)
{
    int a[100],i,j,n,t,k;
    scanf("%d",&n);
    for (i=0;i<n;i++)
        scanf("%d",&a[i]);
    for (i=0;i<n-1;i++)
    {
        for (j=0;j<n-1;j++)
        {
            if(a[j+1]>a[j])
            {
                t=a[j+1];
                a[j+1]=a[j];
                a[j]=t;
            }
        }
    }
    for (i=1;i<n;i++)
    {
        if (a[i]==a[i-1])
        {
            for (j=i;j<n;j++)
                a[j]=a[j+1];
            n--;
            i--;
        }
    }
    scanf("%d",&k);
    printf("%d",a[k-1]);
    return 0;
}
