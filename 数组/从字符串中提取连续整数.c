/*【问题描述】从键盘输入一个字符串，分别将其中每组连续的数字转换为相应的整数，并统计整数的个数，依次输出整数的个数和每个整数乘以2的积（假定不会超出整数范围），如字符串中无数字，则输出0。

【输入形式】一个字符串。

【输出形式】整数的个数和每个整数乘以2的积（以一个空格分隔）。

【输入样例1】ads67ef-u821;Sa(hg)0673 9t#C450360222

【输出样例1】5 134 1642 1346 18 900720444

【输入样例2】sdAnhwRiou&rtio#(xyz)

【输出样例2】0*/
#include<stdio.h>
int main(void)
{
    int a[20],i=0,j,n=0,b=0;
    char c[100];
    while ((c[i]=getchar())!='\n'&&c[i]!=EOF)
    {
        if (c[i]>='0'&&c[i]<='9')
        {
            b=b*10+(int)(c[i]-'0');
        }
        else
        {
            if (b!=0)
            {
                n++;
                a[n]=b;
            }
            b=0;
        }
        i++;
    }
    if (b!=0)
    {
        n++;
        a[n]=b;
    }
    printf("%d",n);
    for (i=1;i<=n;i++)
        printf(" %d",2*a[i]);
    return 0;
}
